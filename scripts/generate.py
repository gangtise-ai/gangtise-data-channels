#!/usr/bin/env python3
"""Generate core + handlers for MCP/CLI into a `_generated/` tree.

Sources (hand-edited):
  core/src/gangtise_core/
  skills/openapi/*/scripts/
  skills/openapi/*/references/
  skills/openapi/*/SKILL.md, infos.json   (-> handlers/<pkg>/skill.json, MCP skill summary)

Skills are standalone: each carries its own scripts/gts_auth.py, gts_runtime.py and _launch.py
(identical across skills, enforced by scripts/check_skills.py). Nothing is written into skills.
When syncing handlers into MCP/CLI, the shared files are dropped and their imports rewritten:
  from .gts_auth import     -> from gangtise_core.auth import
  from .gts_runtime import  -> from gangtise_core.skill_runtime import

Outputs (do not hand-edit):
  mcp/src/_generated/{gangtise_core,handlers}/
  mcp/src/_use_generated.py
  cli/src/_generated/{gangtise_core,handlers}/
  cli/src/_use_generated.py

Usage:
  python3 scripts/generate.py
  python3 scripts/generate.py --check
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import shutil
import sys
from pathlib import Path
from typing import Dict, Iterable, List, Optional

from check_skills import SHARED_FILES, run_checks

ROOT = Path(__file__).resolve().parents[1]
CORE_SRC = ROOT / "core" / "src" / "gangtise_core"
OPENAPI = ROOT / "skills" / "openapi"
MCP_SRC = ROOT / "mcp" / "src"
CLI_SRC = ROOT / "cli" / "src"

GENERATED = "_generated"
BANNER_LINE = "# GENERATED FILE. Do not edit."
REGEN_LINE = "# Regenerate: python3 scripts/generate.py"

SKIP_DIR_NAMES = {
    GENERATED,
    "_core",
    "__pycache__",
    ".authorization",
    ".venv",
}
SKIP_FILE_NAMES = set(SHARED_FILES)
SKIP_SUFFIXES = {".pyc", ".pyo"}

# Skill-local shared modules -> the gangtise_core modules MCP/CLI adapters use.
HANDLER_IMPORT_REWRITES = (
    (re.compile(r"^(\s*)from \.gts_auth import\b", re.MULTILINE), r"\1from gangtise_core.auth import"),
    (re.compile(r"^(\s*)from \.gts_runtime import\b", re.MULTILINE), r"\1from gangtise_core.skill_runtime import"),
)

USE_GENERATED_PY = f'''{BANNER_LINE}
{REGEN_LINE}
"""Insert sibling `{GENERATED}/` onto sys.path. MCP/CLI must not import repo core/src."""
from __future__ import annotations

import sys
from pathlib import Path

_HERE = Path(__file__).resolve().parent
_GEN = _HERE / "{GENERATED}"
if not (_GEN / "gangtise_core").is_dir():
    sys.stderr.write(
        f"missing {{_GEN / 'gangtise_core'}}\\n"
        "From repo root run: python3 scripts/generate.py\\n"
    )
    raise SystemExit(1)
_s = str(_GEN)
if _s not in sys.path:
    sys.path.insert(0, _s)
'''

DO_NOT_EDIT = """# DO NOT EDIT FILES IN THIS DIRECTORY

Generated by `python3 scripts/generate.py`.

- Edit `core/src/gangtise_core/` for shared runtime.
- Edit `skills/openapi/<skill>/scripts/` and `references/` for handlers.
- Then re-run generate. Hand-edits here will be overwritten and fail `--check`.

Layout:
  _generated/gangtise_core/
  _generated/handlers/<pkg>/
"""


def _rel(path: Path) -> str:
    try:
        return path.relative_to(ROOT).as_posix()
    except ValueError:
        return path.as_posix()


def _sha256_text(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def _with_banner(content: str, source: str) -> str:
    banner = f"{BANNER_LINE} Source: {source}\n{REGEN_LINE}\n"
    lines = content.splitlines(keepends=True)
    if lines and lines[0].startswith(BANNER_LINE):
        drop = 1
        if len(lines) > 1 and lines[1].startswith("# Regenerate:"):
            drop = 2
        if len(lines) > drop and lines[drop].strip() == "":
            drop += 1
        lines = lines[drop:]
        content = "".join(lines)
        lines = content.splitlines(keepends=True)
    if lines and lines[0].startswith("#!"):
        rest = "".join(lines[1:])
        return lines[0] + banner + rest
    return banner + content


def _iter_openapi_skills() -> List[Path]:
    if not OPENAPI.is_dir():
        return []
    out: List[Path] = []
    for child in sorted(OPENAPI.iterdir()):
        if child.is_dir() and (child / "scripts").is_dir():
            out.append(child)
    return out


def _rewrite_handler_imports(text: str) -> str:
    for pattern, repl in HANDLER_IMPORT_REWRITES:
        text = pattern.sub(repl, text)
    return text


def _copy_file_payloads(src_root: Path, *, source_prefix: str, rewrite_imports: bool = False) -> Dict[str, str]:
    files: Dict[str, str] = {}
    for path in sorted(src_root.rglob("*")):
        if not path.is_file():
            continue
        rel_parts = path.relative_to(src_root).parts
        if any(part in SKIP_DIR_NAMES for part in rel_parts[:-1]):
            continue
        if path.name in SKIP_FILE_NAMES or path.suffix in SKIP_SUFFIXES:
            continue
        rel = path.relative_to(src_root).as_posix()
        try:
            text = path.read_text(encoding="utf-8")
        except UnicodeDecodeError:
            continue
        source = f"{source_prefix}/{rel}"
        if rewrite_imports and path.suffix == ".py":
            text = _rewrite_handler_imports(text)
        if path.suffix in {".py", ".yaml", ".yml", ".md"}:
            text = _with_banner(text, source)
        files[rel] = text
    return files


def _core_payloads() -> Dict[str, str]:
    files: Dict[str, str] = {}
    for path in sorted(CORE_SRC.rglob("*")):
        if not path.is_file():
            continue
        if any(part in SKIP_DIR_NAMES for part in path.relative_to(CORE_SRC).parts):
            continue
        if path.suffix in SKIP_SUFFIXES:
            continue
        rel = path.relative_to(CORE_SRC).as_posix()
        text = path.read_text(encoding="utf-8")
        if path.suffix == ".py":
            text = _with_banner(text, f"core/src/gangtise_core/{rel}")
        files[rel] = text
    return files


def _frontmatter_description(skill_md: Path) -> str:
    if not skill_md.is_file():
        return ""
    lines = skill_md.read_text(encoding="utf-8").splitlines()
    if not lines or lines[0].strip() != "---":
        return ""
    for line in lines[1:]:
        if line.strip() == "---":
            break
        if line.startswith("description:"):
            value = line.split(":", 1)[1].strip()
            if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
                value = value[1:-1]
            return value.strip()
    return ""


def _short_summary(description: str, *, min_len: int = 30, max_len: int = 160) -> str:
    out = ""
    for sentence in description.replace("。", "。\n").splitlines():
        out += sentence.strip()
        if len(out) >= min_len:
            break
    return out if len(out) <= max_len else out[: max_len - 1] + "…"


def _skill_meta_json(skill_dir: Path) -> str:
    description = _frontmatter_description(skill_dir / "SKILL.md")
    summary = ""
    infos = skill_dir / "infos.json"
    if infos.is_file():
        try:
            summary = str(json.loads(infos.read_text(encoding="utf-8")).get("summary") or "").strip()
        except ValueError:
            summary = ""
    meta = {
        "name": skill_dir.name,
        "summary": summary or _short_summary(description),
        "description": description,
    }
    return json.dumps(meta, indent=2, ensure_ascii=False) + "\n"


def _handler_payloads(skill_dir: Path) -> Dict[str, str]:
    pkg = skill_dir.name.replace("-", "_")
    files: Dict[str, str] = {f"{pkg}/skill.json": _skill_meta_json(skill_dir)}
    scripts = skill_dir / "scripts"
    if scripts.is_dir():
        for rel, text in _copy_file_payloads(
            scripts, source_prefix=f"skills/openapi/{skill_dir.name}/scripts", rewrite_imports=True
        ).items():
            files[f"{pkg}/{rel}"] = text
    refs = skill_dir / "references"
    if refs.is_dir():
        for rel, text in _copy_file_payloads(
            refs, source_prefix=f"skills/openapi/{skill_dir.name}/references"
        ).items():
            files[f"{pkg}/references/{rel}"] = text
    init_rel = f"{pkg}/__init__.py"
    if init_rel not in files:
        files[init_rel] = _with_banner("", f"generated:{init_rel}")
    return files


def _origin_json(sources: Dict[str, str]) -> str:
    hashed = {k: _sha256_text(v) for k, v in sorted(sources.items())}
    return (
        json.dumps(
            {
                "generator": "scripts/generate.py",
                "layout": "_generated/gangtise_core[+handlers]",
                "sources": hashed,
            },
            indent=2,
            ensure_ascii=False,
        )
        + "\n"
    )


def _tree_for_mcp_cli() -> Dict[str, str]:
    files: Dict[str, str] = {}
    sources: Dict[str, str] = {}
    for rel, text in _core_payloads().items():
        files[f"gangtise_core/{rel}"] = text
        sources[f"core/src/gangtise_core/{rel}"] = text
    for skill in _iter_openapi_skills():
        for rel, text in _handler_payloads(skill).items():
            files[f"handlers/{rel}"] = text
            sources[f"handlers/{rel}"] = text
    files["DO_NOT_EDIT"] = DO_NOT_EDIT
    files["origin.json"] = _origin_json(sources)
    return files


def _write_tree(dest: Path, files: Dict[str, str], *, check: bool) -> List[str]:
    mismatches: List[str] = []
    if not check:
        if dest.exists():
            shutil.rmtree(dest)
        dest.mkdir(parents=True)
    expected = set(files)
    for rel, text in files.items():
        path = dest / rel
        if check:
            if not path.is_file():
                mismatches.append(f"missing {_rel(path)}")
                continue
            got = path.read_text(encoding="utf-8")
            if got != text:
                mismatches.append(f"stale {_rel(path)}")
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
    if check and dest.is_dir():
        for path in dest.rglob("*"):
            if not path.is_file():
                continue
            rel_parts = path.relative_to(dest).parts
            if any(part in SKIP_DIR_NAMES for part in rel_parts):
                continue
            if path.suffix in SKIP_SUFFIXES or path.name in SKIP_FILE_NAMES:
                continue
            rel = path.relative_to(dest).as_posix()
            if rel not in expected:
                mismatches.append(f"extra {_rel(path)}")
    return mismatches


def _write_text(path: Path, text: str, *, check: bool) -> List[str]:
    if check:
        if not path.is_file():
            return [f"missing {_rel(path)}"]
        if path.read_text(encoding="utf-8") != text:
            return [f"stale {_rel(path)}"]
        return []
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    return []


def _rm_legacy_vendored_core(scripts: Path) -> None:
    for name in (GENERATED, "_core"):
        legacy = scripts / name
        if legacy.exists():
            shutil.rmtree(legacy)


def generate(*, check: bool) -> List[str]:
    if not CORE_SRC.is_dir():
        raise SystemExit(f"missing {CORE_SRC}")
    skills = _iter_openapi_skills()
    if not skills:
        raise SystemExit(f"no openapi skills under {OPENAPI}")
    product_tree = _tree_for_mcp_cli()
    mismatches: List[str] = []
    mismatches.extend(_write_tree(MCP_SRC / GENERATED, product_tree, check=check))
    mismatches.extend(_write_tree(CLI_SRC / GENERATED, product_tree, check=check))
    mismatches.extend(_write_text(MCP_SRC / "_use_generated.py", USE_GENERATED_PY, check=check))
    mismatches.extend(_write_text(CLI_SRC / "_use_generated.py", USE_GENERATED_PY, check=check))
    return mismatches


def main(argv: Optional[Iterable[str]] = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit 1 if generated trees are missing or stale (do not write)",
    )
    args = parser.parse_args(list(argv) if argv is not None else None)
    if not args.check:
        for skill in _iter_openapi_skills():
            _rm_legacy_vendored_core(skill / "scripts")
    skill_errors = run_checks()
    if skill_errors:
        print("skill checks failed (scripts/check_skills.py):", file=sys.stderr)
        for line in skill_errors:
            print(f"  {line}", file=sys.stderr)
        return 1
    mismatches = generate(check=args.check)
    if args.check:
        if mismatches:
            print("generated files are stale or missing:", file=sys.stderr)
            for line in mismatches[:80]:
                print(f"  {line}", file=sys.stderr)
            if len(mismatches) > 80:
                print(f"  ... {len(mismatches) - 80} more", file=sys.stderr)
            print("Run: python3 scripts/generate.py", file=sys.stderr)
            return 1
        print("generated files are up to date")
        return 0

    print(f"skill checks passed ({len(_iter_openapi_skills())} skills)")
    print(f"generated core+handlers -> {_rel(MCP_SRC / GENERATED)}")
    print(f"generated core+handlers -> {_rel(CLI_SRC / GENERATED)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
